function value = local_optional(row, name)
if ismember(name, row.Properties.VariableNames)
    value = row.(name);
else
    value = NaN;
end
end

function old = local_align_table(old, row)
targetNames = row.Properties.VariableNames;
for k = 1:numel(targetNames)
    name = targetNames{k};
    if ~ismember(name, old.Properties.VariableNames)
        old.(name) = local_missing_column(row.(name), height(old));
    end
end
old = old(:, targetNames);
end

function values = local_missing_column(template, n)
if isstring(template)
    values = strings(n, 1);
elseif iscellstr(template)
    values = repmat({''}, n, 1);
elseif islogical(template)
    values = false(n, 1);
else
    values = nan(n, 1);
end
end
